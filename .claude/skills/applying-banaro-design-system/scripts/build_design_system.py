class Specimens:
    def __init__(self):
        self.uid = 0

    def namespace(self, root: K.Node) -> None:
        """Give every id in a specimen copy a unique prefix and rewrite references to it."""
        self.uid += 1
        ids = {el.get("id"): f"s{self.uid}-{el.get('id')}" for el in root.elements() if el.get("id")}
        names = {}
        for el in root.elements():
            if el.get("id"):
                el.set("id", ids[el.get("id")])
            for attr in ("for", "aria-controls", "aria-labelledby", "aria-describedby", "popovertarget", "list", "form", "anchor"):
                if el.get(attr):
                    el.set(attr, " ".join(ids.get(x, x) for x in el.get(attr).split()))
            if el.get("name") and el.tag in ("input", "select", "textarea"):
                names.setdefault(el.get("name"), f"s{self.uid}-{el.get('name')}")
                el.set("name", names[el.get("name")])
            href = el.get("href")
            if href and href.startswith("#") and href[1:] in ids:
                el.set("href", "#" + ids[href[1:]])
            for attr in ("data-open-dialog",):
                if el.get(attr) in ids:
                    el.set(attr, ids[el.get(attr)])

    def target(self, root: K.Node, source: K.Source) -> K.Node | None:
        sel = source.meta.get("target")
        if sel:
            hit = root.select_one(sel)
            if hit:
                return hit
        return root.select_one("button:not([disabled]), a[href], input, textarea, select, summary") or root.first_element()

    def apply_state(self, root: K.Node, source: K.Source, state: str, error_text: str) -> None:
        state = state.strip().lower()
        if state == "default":
            return
        target = self.target(root, source)
        if target is None:
            return
        if state in ("hover", "focus", "active", "focus-visible"):
            target.set("data-state", state)
        elif state == "disabled":
            for ctl in root.select("button, input, select, textarea"):
                ctl.set("disabled", "")
            if target.tag == "a":
                target.remove("href")
                target.set("aria-disabled", "true")
                target.set("tabindex", "-1")
            elif target.tag not in ("button", "input", "select", "textarea"):
                target.set("data-state", "disabled")
        elif state in ("loading", "busy", "submitting"):
            target.set("aria-busy", "true")
            if target.tag == "button" and "btn" in target.classes:
                spinner = K.parse_fragment('<span class="spinner" aria-hidden="true"></span>').first_element()
                target.insert(0, spinner)
        elif state in ("selected", "checked", "pressed", "on"):
            if target.tag == "input" and (target.get("type") or "") in ("checkbox", "radio"):
                target.set("checked", "")
            elif target.get("role") in ("tab", "option", "row", "gridcell") or target.tag == "tr":
                target.set("aria-selected", "true")
            elif target.tag == "button" and state in ("pressed", "selected"):
                target.set("aria-pressed", "true")
            else:
                target.set("data-state", "selected")
                if target.tag in ("article", "li", "div") and state == "selected":
                    target.set("aria-selected", "true") if target.get("role") else None
        elif state == "invalid":
            target.set("aria-invalid", "true")
            if target.tag in ("input", "textarea", "select"):
                self.uid += 1
                err_id = f"s{self.uid}-error"
                described = (target.get("aria-describedby") or "").split()
                target.set("aria-describedby", " ".join(described + [err_id]))
                error = K.parse_fragment(f'<p class="field__error" id="{err_id}"><svg class="icon icon--sm" viewBox="0 0 24 24" aria-hidden="true"><circle cx="12" cy="12" r="9"/><path d="M12 7.5v5.5M12 16.5h.01"/></svg>{esc(error_text)}</p>').first_element()
                anchor = target
                while anchor.parent is not None and anchor.parent.tag not in ("#root",) and "field" not in anchor.parent.classes \
                        and anchor.parent.tag not in ("label", "fieldset", "div", "form"):
                    anchor = anchor.parent
                anchor.insert_after(error)
        elif state == "read-only":
            target.set("readonly", "")
        elif state == "required":
            target.set("required", "")
            target.set("aria-required", "true")
        elif state == "indeterminate":
            target.set("data-indeterminate", "true")
        elif state in ("open", "expanded"):
            if target.tag == "summary" and target.parent is not None and target.parent.tag == "details":
                target.parent.set("open", "")
            else:
                target.set("aria-expanded", "true")
                target.set("data-state", "open")
        elif state == "current":
            target.set("aria-current", "page")
        else:
            target.set("data-state", state)

    def render(self, markup: str, source: K.Source, state: str = "default", size: str | None = None, wrap: bool = True) -> str:
        root = K.parse_fragment(markup)
        for h in root.select("h1"):
            h.tag = "h3"
        self.apply_state(root, source, state, source.meta.get("error", "Check this answer before saving."))
        if size and source.meta.get("size-class"):
            target = self.target(root, source)
            if target is not None:
                for cls in source.meta["size-class"].replace("{size}", size).split():
                    target.add_class(cls)
        self.namespace(root)
        inner = root.html()
        if not wrap:
            return inner
        layout = " ds-demo--block" if source.meta.get("layout", "block") == "block" else ""
        return f'<div class="ds-demo{layout}" data-demo-component="{source.slug}">{inner}</div>'


