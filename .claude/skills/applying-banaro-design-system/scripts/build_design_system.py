def sync_theme_blocks(tokens_css: str) -> str:
    """Regenerate the auto-dark copy and the explicit light reset from :root and the dark block."""
    light = K.root_declarations(tokens_css)
    dark_body = K.dark_block_body(tokens_css)
    dark = K.dark_declarations(tokens_css)
    if not dark:
        return tokens_css
    auto = "\n".join("    " + line.strip() for line in dark_body.strip().splitlines() if line.strip())
    reset_lines = []
    for name in dark:
        if name in light:
            reset_lines.append(f"  {name}: {light[name].strip()};")
    reset_lines.append("  color-scheme: light;")
    generated = (
        "/* generated:start */\n"
        "/* Generated by build_design_system.py from :root and the dark block. Do not edit. */\n"
        "@media (prefers-color-scheme: dark) {\n  :root:not([data-theme=\"light\"]) {\n" + auto + "\n  }\n}\n\n"
        "/* An explicit light specimen resets inherited dark roles. */\n"
        "[data-theme=\"light\"] {\n" + "\n".join(reset_lines) + "\n}\n"
        "/* generated:end */"
    )
    if "/* generated:start */" not in tokens_css:
        return tokens_css.replace("/* dark:end */", "/* dark:end */\n\n" + generated, 1)
    return re.sub(r"/\* generated:start \*/.*?/\* generated:end \*/", lambda _m: generated, tokens_css, flags=re.S)


