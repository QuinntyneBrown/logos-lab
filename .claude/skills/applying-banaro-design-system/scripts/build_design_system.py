def section(sid, body, na=None, title=None):
    title = title or K.SECTION_TITLES.get(sid, sid.replace("-", " ").capitalize())
    na_attr = f' data-na="{esc(na.replace("`", ""), quote=True)}"' if na else ""
    na_note = f'<p class="ds-na">{K.inline(na)}</p>' if na else ""
    return f'<section class="ds-section" id="{sid}"{na_attr}><h2><a href="#{sid}">{esc(title)}</a></h2>{na_note}{body}</section>'


def example(body, caption, canvas=""):
    extra = f" ds-example__canvas--{canvas}" if canvas else ""
    return f'<div class="ds-example"><div class="ds-example__canvas ds-example__canvas--stack{extra}">{body}</div><p class="ds-example__caption"><span>{esc(caption)}</span></p></div>'


def themes(render_fn, stack=False):
    return f'<div class="ds-themes{" ds-themes--stack" if stack else ""}">' + "".join(f'<div data-theme="{t}">{render_fn(t)}</div>' for t in ("light", "dark")) + "</div>"


def token_table(names):
    rows = []
    for n in names:
        swatch = f'<i data-token="{n}" data-swatch></i>' if n.startswith(("--color-", "--palette-")) else ""
        rows.append([f'<span class="ds-swatch-cell">{swatch}<code>{n}</code></span>' if swatch else f"<code>{n}</code>",
                     f'<span data-theme="light" data-token="{n}"></span>', f'<span data-theme="dark" data-token="{n}"></span>'])
    return K.table(["Token", "Light", "Dark"], rows)


def pair(fg, bg, minimum=4.5, title="Text contrast"):
    return f'<div class="ds-pair"><span>{esc(title)} · <code>{fg}</code> on <code>{bg}</code></span><span class="ds-pair__ratio" data-contrast="{fg}|{bg}" data-min="{minimum}"></span></div>'


class Site:
    def __init__(self, root: Path):
        self.root = root
        self.config = K.load_config(root)
        self.app = self.config.get("app", "Product")
        self.version = self.config.get("version", "1.0")
        self.sources = K.load_sources(root)
        swaps = {"{{app}}": self.app, "{{app_lower}}": self.app.lower(), "{{prefix}}": self.config.get("prefix", "bn")}
        for items in self.sources.values():
            for s in items:
                for key, text in s.sections.items():
                    for a, b in swaps.items():
                        text = text.replace(a, b)
                    s.sections[key] = text
                for key, value in s.meta.items():
                    if isinstance(value, str):
                        for a, b in swaps.items():
                            value = value.replace(a, b)
                        s.meta[key] = value
        self.tokens_css = (root / "tokens/tokens.css").read_text(encoding="utf-8")
        self.components_css = (root / "assets/components.css").read_text(encoding="utf-8")
        self.blocks = K.css_blocks(self.components_css)
        self.token_names = K.token_names(self.tokens_css)
        self.mocks = K.mocks_root_for(root)
        self.mock_index = K.mock_class_index(self.mocks)
        self.has_mock_gallery = (self.mocks / "index.html").exists()
        self.spec = Specimens()
        self.problems: list = []
        self.warnings: list = []

    # navigation ----------------------------------------------------------
    def nav(self, prefix: str) -> str:
        out = [f'<nav class="ds-nav" aria-label="Design system"><div class="ds-nav__brand"><a href="{prefix}index.html">{esc(self.app)} DS</a>'
               '<button class="ds-theme-toggle" type="button" aria-pressed="false">☾ Dark</button></div>']
        for kind, label in (("foundations", "Foundations"), ("components", "Components"), ("patterns", "Patterns")):
            items = "".join(f'<li><a href="{prefix}{kind}/{s.slug}.html">{esc(s.title)}</a></li>' for s in self.sources[kind])
            out.append(f"<details open><summary>{label}</summary><ul>{items}</ul></details>")
        out.append("</nav>")
        return "".join(out)

    def shell(self, folder: str, slug: str, title: str, lead: str, body: str, toc: list, kicker: str, pills: list) -> str:
        prefix = "../" if folder else ""
        mocks_link = ""
        if self.has_mock_gallery:
            mocks_link = f' · <a href="{prefix}../mocks/index.html">Mocks</a>'
        toc_html = "".join(f'<li><a href="#{s}">{esc(K.SECTION_TITLES.get(s, s.replace("-", " ").capitalize()))}</a></li>' for s in toc)
        pills_html = "".join(f'<span class="ds-pill{" ds-pill--" + kind if kind else ""}">{esc(text)}</span>' for text, kind in pills)
        scripts = f'<script src="{prefix}assets/ds.js"></script><script src="{prefix}assets/examples.js"></script>'
        return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{esc(title)} — {esc(self.app)} design system</title>
<meta name="description" content="{esc(lead, quote=True)}">
<link rel="stylesheet" href="{prefix}assets/fonts/fonts.css">
<link rel="stylesheet" href="{prefix}tokens/tokens.css">
<link rel="stylesheet" href="{prefix}assets/components.css">
<link rel="stylesheet" href="{prefix}assets/ds.css">
</head>
<body id="top">
<a class="ds-skip-link" href="#main">Skip to content</a>
<div class="ds-shell">
{self.nav(prefix)}
<main class="ds-main" id="main" tabindex="-1">
<header class="ds-header"><p class="ds-kicker">{esc(kicker)}</p><h1>{esc(title)}</h1><p class="ds-lead">{esc(lead)}</p><div class="ds-meta">{pills_html}</div><ul class="ds-toc">{toc_html}</ul></header>
{body}
<footer class="ds-footer"><span>{esc(self.app)} design system v{esc(self.version)}{mocks_link}</span><a href="#top">Back to top</a></footer>
</main>
</div>
{scripts}
</body>
</html>
"""

    def write(self, rel: str, content: str) -> None:
        path = self.root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")

    def mock_link(self, path: Path, prefix: str) -> str:
        rel = path.relative_to(self.mocks).as_posix()
        return f'<a href="{prefix}../mocks/{rel}">{esc(rel)}</a>'

    # components ---------------------------------------------------------
    def variants(self, s: K.Source) -> list:
        """[(name, markup)] from '### name' subsections of Variants."""
        out = []
        for title, body in K.subsections(s.sections.get("variants", "")):
            codes = K.fences(body)
            if title and codes:
                out.append((title, codes[0], K.strip_fences(body)))
        return out

    def state_overrides(self, s: K.Source) -> dict:
        overrides = {}
        for title, body in K.subsections(s.sections.get("states", "")):
            codes = K.fences(body)
            if not title or not codes:
                continue
            if "/" in title:
                variant, state = [x.strip().lower() for x in title.split("/", 1)]
            else:
                variant, state = "*", title.strip().lower()
            overrides[(variant, state)] = codes[0]
        return overrides

    def component_tokens(self, s: K.Source) -> list:
        explicit = s.meta.get("tokens")
        if explicit:
            return [t for t in explicit if t in self.token_names]
        block = self.blocks.get(s.slug, "")
        refs = [n for n in K.var_refs(block) if n in self.token_names]
        return refs

    def component_page(self, s: K.Source) -> str:
        variants = self.variants(s)
        if not variants:
            self.problems.append(f"src/components/{s.slug}.md: Variants needs at least one '### name' with an html fence")
            return ""
        if s.slug not in self.blocks and not s.meta.get("css") == "none":
            self.warnings.append(f"src/components/{s.slug}.md: no '@component {s.slug}' block in assets/components.css")
        for sid in K.COMPONENT_SECTIONS:
            if sid not in s.sections and sid not in ("tokens", "code", "sources", "theming", "sizes", "states", "variants", "anatomy"):
                self.problems.append(f"src/components/{s.slug}.md: missing '## {K.SECTION_TITLES[sid]}' (write 'N/A: reason' if it does not apply)")
        base_name, base_markup, _ = variants[0]
        states = [x.lower() for x in (s.meta.get("states") or ["default"])]
        if "default" not in states:
            states.insert(0, "default")
        overrides = self.state_overrides(s)
        md = lambda text: K.markdown(text, live_html=lambda code: example(self.spec.render(code, s), "Live specimen"))  # noqa: E731
        uses = K.usage(s, self.mock_index)
        body = []

        # overview
        provenance = (f"Used in {len(uses)} mock state{'s' if len(uses) != 1 else ''}." if uses
                      else "Not used in the mocks yet." if self.mock_index else "Kit component; mocks have not been written yet.")
        body.append(section("overview", md(s.sections.get("overview", s.summary)) + f"<p>{provenance}</p>"))

        # anatomy
        anat = re.sub(r"\n[ \t]+(?=\S)", " ", s.sections.get("anatomy", ""))  # join wrapped list lines
        anat_code = (K.fences(anat) or [base_markup])[0]
        parts = re.findall(r"^\s*\d+\.\s+(.*)$", K.strip_fences(anat), re.M)
        items = []
        for part in parts:
            m = re.match(r"\*\*(.+?)\*\*\s*[—:-]\s*(.*)", part)
            name, desc = (m.group(1), m.group(2)) if m else (part, "")
            items.append(f"<li><div><b>{K.inline(name)}</b><small>{K.inline(desc)}</small></div></li>")
        anatomy_html = f'<div class="ds-anatomy"><figure class="ds-anatomy__figure">{self.spec.render(anat_code, s)}</figure><ol class="ds-anatomy__list">{"".join(items)}</ol></div>'
        extra = re.sub(r"^\s*\d+\.\s+.*$", "", K.strip_fences(anat), flags=re.M).strip()
        body.append(section("anatomy", anatomy_html + (md(extra) if extra else "")))

        # variants
        vhtml = []
        for name, markup, note in variants:
            vhtml.append(f"<h3>{esc(name[:1].upper() + name[1:])}</h3>" + (md(note) if note else "") + example(self.spec.render(markup, s), f"{s.title} · {name}"))
        body.append(section("variants", md(K.strip_fences(K.subsections(s.sections.get("variants", ""))[0][1]) if K.subsections(s.sections.get("variants", "")) and not K.subsections(s.sections.get("variants", ""))[0][0] else "") + "".join(vhtml)))

        # sizes
        sizes_text = s.sections.get("sizes", "")
        sizes = s.meta.get("sizes") or []
        na = K.na_reason(sizes_text) if sizes_text else (None if sizes else "One content-driven size; the component follows the shared spacing roles.")
        if sizes:
            shown = "".join(example(self.spec.render(base_markup, s, size=size), f"{s.title} · {size}") for size in sizes)
            body.append(section("sizes", md(sizes_text) + shown))
        else:
            body.append(section("sizes", "" if na else md(sizes_text), na=na))

        # states
        matrix_variants = [v for v in variants if not s.meta.get("matrix-variants") or v[0] in s.meta["matrix-variants"]]

        def matrix(theme):
            rows = []
            cell = s.meta.get("matrix-cell", "")
            td_open = f'<td style="min-width: {esc(cell, quote=True)}">' if re.fullmatch(r"\d+(\.\d+)?rem", cell) else "<td>"
            for name, markup, _ in matrix_variants:
                cells = []
                for state in states:
                    override = overrides.get((name.lower(), state)) or overrides.get(("*", state))
                    cells.append(td_open + (self.spec.render(override, s) if override else self.spec.render(markup, s, state)) + "</td>")
                rows.append(f'<tr><th scope="row">{esc(name)}</th>{"".join(cells)}</tr>')
            head = "".join(f'<th scope="col">{esc(x.capitalize())}</th>' for x in states)
            mod = "block" if s.meta.get("layout", "block") == "block" else "inline"
            return f'<div class="ds-matrix ds-matrix--{mod}"><table><caption>{esc(s.title)} states · {theme} theme</caption><thead><tr><th scope="col">Variant</th>{head}</tr></thead><tbody>{"".join(rows)}</tbody></table></div>'
        states_note = K.strip_fences(K.subsections(s.sections.get("states", ""))[0][1]) if K.subsections(s.sections.get("states", "")) and not K.subsections(s.sections.get("states", ""))[0][0] else ""
        body.append(section("states", md(states_note) + themes(matrix, stack=True)))

        # responsive
        resp = s.sections.get("responsive", "")
        body.append(section("responsive", md(resp), na=K.na_reason(resp)))

        # theming
        theming = s.sections.get("theming", "Every colour comes from a semantic role, so the dark theme needs no component-specific rules. A light specimen nested under a dark root resets its roles.")
        body.append(section("theming", md(theming) + themes(lambda t: self.spec.render(base_markup, s))))

        # accessibility
        acc = s.sections.get("accessibility", "")
        contrast_specs = [c.strip() for c in s.meta.get("contrast", "").split(";") if c.strip()] or ["--color-fg-default|--color-bg-surface|4.5", "--color-focus-ring|--color-bg-surface|3"]
        pairs_html = []
        for spec in contrast_specs:
            bits = spec.split("|")
            if len(bits) >= 2 and bits[0] in self.token_names and bits[1] in self.token_names:
                minimum = float(bits[2]) if len(bits) > 2 else 4.5
                pairs_html.append(pair(bits[0], bits[1], minimum, "Non-text contrast" if minimum < 4.5 else "Text contrast"))
        body.append(section("accessibility", md(acc) + "<h3>Contrast</h3>" + themes(lambda t: "".join(pairs_html))))

        # content
        content = s.sections.get("content", "")
        body.append(section("content", md(content), na=K.na_reason(content)))

        # do / don't
        dd = []
        for title, text in K.subsections(s.sections.get("do-dont", "")):
            kind = "ds-do" if title.lower().startswith("do") and "don" not in title.lower() else "ds-dont"
            codes = K.fences(text)
            caption = K.inline(" ".join(K.strip_fences(text).split()))
            canvas = self.spec.render(codes[0], s) if codes else (self.spec.render(base_markup, s) if kind == "ds-do" else f"<p>{caption}</p>")
            dd.append(f'<figure class="{kind}"><div class="ds-example__canvas">{canvas}</div><figcaption>{caption}</figcaption></figure>')
        body.append(section("do-dont", f'<div class="ds-dodont">{"".join(dd)}</div>'))

        # tokens
        knobs = s.meta.get("knobs", "")
        knob_rows = []
        for knob in [k.strip() for k in knobs.split(";") if k.strip()]:
            name, _, alias = knob.partition("=")
            knob_rows.append([f"<code>{esc(name.strip())}</code>", K.inline(alias.strip())])
        knob_html = K.table(["Component knob", "Default and variants"], knob_rows) if knob_rows else ""
        body.append(section("tokens", md(s.sections.get("tokens", "")) + knob_html + token_table(self.component_tokens(s))))

        # code
        code = self.spec.render(base_markup, s, wrap=False)
        body.append(section("code", md(s.sections.get("code", "Link `tokens/tokens.css` and `assets/components.css`, then use this markup. The `data-state` attribute only forces a state for review; production code uses real interaction and native attributes.")) + f"<pre><code>{esc(code)}</code></pre>"))

        # sources
        if uses:
            links = "".join(f"<li>{self.mock_link(p, '../')}</li>" for p in uses[:6])
            more = f"<p>And {len(uses) - 6} more mock states.</p>" if len(uses) > 6 else ""
            src = f"<p>Mock states that use <code>{esc(s.meta.get('selector', ''))}</code>:</p><ul>{links}</ul>{more}"
        else:
            src = f"<p>No mock uses <code>{esc(s.meta.get('selector', ''))}</code> yet. Styles live in <a href=\"../assets/components.css\">components.css</a>.</p>"
        body.append(section("sources", src + f"<p>Derived from the Banaro component kit ({esc(s.tier)} tier).</p>"))

        pills = [(s.tier.capitalize() + " component", ""), ("Contrast verified", "ok")]
        if not uses and self.mock_index and s.tier != "core":
            pills.append(("Unused in mocks", "warn"))
        return self.shell("components", s.slug, s.title, s.summary or s.title, "\n".join(body), K.COMPONENT_SECTIONS, f"Components · v{self.version}", pills)

    # patterns -----------------------------------------------------------
    def pattern_page(self, s: K.Source) -> str:
        md = lambda text: K.markdown(text, live_html=lambda code: example(self.spec.render(code, s), "Live specimen"))  # noqa: E731
        body = []
        for sid in K.PATTERN_SECTIONS:
            if sid == "sources":
                continue
            text = s.sections.get(sid)
            if text is None:
                self.problems.append(f"src/patterns/{s.slug}.md: missing '## {K.SECTION_TITLES[sid]}'")
                text = ""
            if sid == "do-dont":
                dd = []
                for title, sub in K.subsections(text):
                    kind = "ds-do" if title.lower().startswith("do") and "don" not in title.lower() else "ds-dont"
                    codes = K.fences(sub)
                    caption = K.inline(" ".join(K.strip_fences(sub).split()))
                    canvas = self.spec.render(codes[0], s) if codes else f"<p>{caption}</p>"
                    dd.append(f'<figure class="{kind}"><div class="ds-example__canvas">{canvas}</div><figcaption>{caption}</figcaption></figure>')
                body.append(section(sid, f'<div class="ds-dodont">{"".join(dd)}</div>'))
            else:
                body.append(section(sid, md(text), na=K.na_reason(text)))
        uses = K.usage(s, self.mock_index)
        components = [c for c in s.meta.get("components", "").replace(" ", "").split(",") if c]
        links = "".join(f'<li><a href="../components/{c}.html">{esc(next((x.title for x in self.sources["components"] if x.slug == c), c))}</a></li>'
                        for c in components if any(x.slug == c for x in self.sources["components"]))
        src = (f"<h3>Components</h3><ul>{links}</ul>" if links else "")
        if uses:
            src += "<h3>In the mocks</h3><ul>" + "".join(f"<li>{self.mock_link(p, '../')}</li>" for p in uses[:6]) + "</ul>"
        body.append(section("sources", src or "<p>Applies across the product.</p>"))
        return self.shell("patterns", s.slug, s.title, s.summary or s.title, "\n".join(body), K.PATTERN_SECTIONS, f"Patterns · v{self.version}", [("Pattern", "")])

    # foundations --------------------------------------------------------
    def topic_tokens(self, topic):
        return [n for n in self.token_names if K.token_topic(n) == topic]

    def foundation_specimens(self, topic) -> str:
        names = self.topic_tokens(topic)
        if topic == "color":
            families: dict = {}
            for n in names:
                if n.startswith("--palette-"):
                    fam = n.removeprefix("--palette-").rsplit("-", 1)[0] if re.search(r"-\d+$", n) else "base"
                    families.setdefault(fam, []).append(n)
            ramps = "".join(f'<h3>{esc(fam.capitalize())}</h3><div class="ds-ramp">' + "".join(
                f'<span data-token="{n}" data-swatch data-step="{n.rsplit("-", 1)[-1]}"></span>' for n in fam_names) + "</div>" for fam, fam_names in families.items())
            roles = [n for n in names if n.startswith("--color-")]
            role_cards = "".join(f'<div class="ds-color-chip"><span class="ds-color-chip__swatch" data-token="{n}" data-swatch></span><code>{n}</code></div>' for n in roles)
            pairs_path = self.root / "tokens/contrast-pairs.json"
            pairs = json.loads(pairs_path.read_text(encoding="utf-8")).get("pairs", []) if pairs_path.exists() else []
            pair_html = themes(lambda t: "".join(pair(p["fg"], p["bg"], p.get("min", 4.5), p.get("note", "Pair")) for p in pairs[:24]))
            return ("<h3>Palette ramps</h3>" + ramps + "<h3>Semantic roles</h3>" + themes(lambda t: f'<div class="ds-color-grid">{role_cards}</div>')
                    + f"<h3>Declared contrast pairs</h3><p>{len(pairs)} pairs are checked by <code>check_contrast.py</code> in both themes; the first 24 are shown live.</p>" + pair_html)
        if topic == "typography":
            roles = [n for n in names if n.startswith("--text-")]
            return "".join(f'<div class="ds-specimen"><span class="ds-specimen__meta">{n}</span><span style="font: var({n})">Quiet work, done well</span></div>' for n in roles)
        if topic == "spacing":
            return '<div class="ds-scale">' + "".join(f'<div class="ds-scale__row"><code>{n}</code><span data-token="{n}"></span><span class="ds-scale__bar" style="--size: var({n})"></span></div>' for n in names) + "</div>"
        if topic == "shape":
            radii = [n for n in names if n.startswith("--radius-")]
            return '<div class="ds-scale">' + "".join(f'<div class="ds-scale__row"><code>{n}</code><span data-token="{n}"></span><span class="ds-scale__box" style="--size: var({n})"></span></div>' for n in radii) + "</div>"
        if topic == "elevation":
            shadows = [n for n in names if re.match(r"--shadow-\d$", n)]
            return themes(lambda t: '<div class="ds-shadow-grid">' + "".join(f'<div style="--shadow: var({n})">{n}</div>' for n in shadows) + "</div>")
        if topic == "motion":
            durations = [n for n in names if n.startswith("--duration-")]
            return '<div class="stack">' + "".join(
                f'<div class="ds-motion-demo ds-motion-row" style="--demo-duration: var({n})"><button class="btn btn--quiet btn--sm" type="button" data-motion-run>Play {n.removeprefix("--duration-")}</button><code>{n}</code><span class="dot" aria-hidden="true"></span></div>' for n in durations if n != "--duration-instant") + "</div>"
        if topic == "layout":
            return '<div class="ds-grid-demo" aria-hidden="true">' + "".join(f"<div>{i}</div>" for i in range(1, 13)) + "</div><p>Resize the window: 4 columns on phones, 8 from 48rem, 12 from 64rem.</p>"
        if topic == "theming":
            sample = '<div class="card"><p class="eyebrow">Theme</p><p class="card__name">Same roles, two moods</p><p class="card__text">Birch paper by day, lamplight at night.</p><div class="cluster"><button class="btn btn--primary" type="button">Primary action</button><button class="btn btn--quiet" type="button">Secondary</button></div></div>'
            return themes(lambda t: sample)
        if topic == "responsive":
            bps = [n for n in self.token_names if n.startswith("--layout-breakpoint-")]
            return K.table(["Breakpoint", "Value"], [[f"<code>{n}</code>", f'<span data-token="{n}"></span>'] for n in bps])
        if topic == "accessibility":
            return themes(lambda t: pair("--color-fg-default", "--color-bg-canvas") + pair("--color-fg-muted", "--color-bg-surface") + pair("--color-focus-ring", "--color-bg-surface", 3, "Focus indicator") + pair("--color-fg-on-accent", "--color-accent"))
        return ""

    def foundation_page(self, s: K.Source) -> str:
        md = lambda text: K.markdown(text, live_html=lambda code: example(self.spec.render(code, s), "Live specimen"))  # noqa: E731
        body = [section("principles", md(s.sections.get("principles", s.summary)))]
        body.append(section("specimens", self.foundation_specimens(s.slug) + md(s.sections.get("specimens", ""))))
        names = self.topic_tokens(s.slug)
